// Inlines KaTeX's stylesheet and woff2 fonts into a TS module so the plugin works offline.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve("katex/dist/katex.min.css"));
let css = readFileSync(join(dist, "katex.min.css"), "utf8");

// Keep only the woff2 source of each @font-face and embed it as a data URL.
css = css.replace(/src:url\(fonts\/([^)]+?)\.woff2\) format\("woff2"\)(,url\([^)]+\) format\("[^"]+"\))*/g, (_, name) => {
  const b64 = readFileSync(join(dist, "fonts", `${name}.woff2`)).toString("base64");
  return `src:url(data:font/woff2;base64,${b64}) format("woff2")`;
});
if (/url\(fonts\//.test(css)) throw new Error("unreplaced KaTeX font URL");

writeFileSync(
  new URL("../client/generated/katex-css.ts", import.meta.url),
  `// Generated by scripts/gen-katex-css.mjs. Do not edit.\nexport const katexCss = ${JSON.stringify(css)};\n`,
);
console.log(`katex-css.ts: ${(css.length / 1024).toFixed(0)} KiB`);
